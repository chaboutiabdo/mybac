ALTER TABLE ONLY public.video_activity_logs
  ADD CONSTRAINT video_activity_logs_student_id_fkey
  FOREIGN KEY (student_id) REFERENCES public.profiles(user_id) ON DELETE CASCADE;

DELETE FROM public.student_questions_log l
 WHERE NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.user_id = l.student_id);
ALTER TABLE ONLY public.student_questions_log
  ADD CONSTRAINT student_questions_log_student_id_fkey
  FOREIGN KEY (student_id) REFERENCES public.profiles(user_id) ON DELETE CASCADE;
